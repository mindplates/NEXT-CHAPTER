package com.mindplates.nextchapter.application.catalog.port.out;

/**
 * 주제 입력 해소의 레이트 리밋.
 *
 * <p>이 엔드포인트만 따로 막는 이유는 <b>호출 하나가 LLM 을 최대 3번 부르기 때문</b>이다. 사용자 경로를
 * 열면서 이것을 열어 두면 비용 남용 경로가 그대로 생기고, 그 비용은 뼈대당·일일 예산 상한으로 흘러 다른
 * 사용자의 생성까지 막는다.
 *
 * <p>포트로 뺀 이유는 카운터가 <b>인스턴스 간에 공유돼야</b> 하기 때문이다. 프로세스 메모리에 두면 한도가
 * 인스턴스 수만큼 곱해지는데, 그 상태는 에러 없이 조용히 느슨해진다. 구현은 Redis 다.
 *
 * <p>일반적인 엔드포인트 레이트 리밋은 여기 없다 — 운영 성숙(M7)의 몫이다. 지금 전부 만들면 실제 사용
 * 패턴 없이 한도를 정하게 되고, 그 값은 대체로 틀린다.
 */
public interface TopicResolveRateLimitPort {

    /**
     * 이번 호출을 허용할지. 허용하면 사용량을 하나 소비한다.
     *
     * <p>실패했을 때 <b>열어 주지 않는다</b>(fail-closed). 저장소가 죽었을 때 통과시키면 그 순간이 비용
     * 폭주 창구가 되고, 반대로 막으면 사용자가 잠시 주제 입력을 못 하는 것으로 끝난다.
     */
    boolean tryConsume(Long userId);

    /** 한도. 초과 응답에 실어 사용자가 언제 다시 시도할 수 있는지 알게 한다. */
    int limitPerWindow();

    int windowSeconds();
}
