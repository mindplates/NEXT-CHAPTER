package com.mindplates.nextchapter.domain.layer.model;

/**
 * 이해도 구간. 경로 결정과 퀴즈 난이도가 이 값을 본다.
 *
 * <p>연속값(정답률)을 그대로 쓰지 않고 세 구간으로 접는 이유는 두 가지다. 초기 표본이 작아 정답률이
 * 한두 문항에 크게 흔들리고, 무엇보다 <b>신호에 기록해 두면 나중에 보정할 수 있어야</b> 하는데 연속값은
 * 집계에서 다시 구간을 정해야 한다 — 그 구간이 기록 시점과 달라지면 조용히 다른 결론이 나온다.
 */
public enum UnderstandingLevel {

    /** 아직 아무 반응이 없다. 이해도를 <b>모르는 것</b>이고, 낮은 것과 다르다. */
    UNKNOWN,

    /** 막혀 있다 — 선행 챕터로 되돌리거나 보충 블록을 붙일 지점이다. */
    STRUGGLING,

    LEARNING,

    /** 충분히 이해했다 — 심화로 보낼 수 있다. */
    CONFIDENT
}
