package com.mindplates.nextchapter.domain.chapter.model;

/**
 * 챕터 간 관계. 개인 루프(M4)가 "다음에 볼 챕터"를 이 위에서 고른다.
 *
 * <p><b>"다음 챕터"라는 타입을 두지 않는다.</b> 선형 다음을 간선으로 표현하면 그건 목차이고, 챕터를
 * 그래프로 둔 이유가 사라진다. 순서가 필요한 곳에서는 {@link #PREREQUISITE} 와 챕터의 정렬 순서에서
 * 나오게 한다 — 그러면 "선행만 채우면 어느 순서로도 갈 수 있다"가 표현된다.
 */
public enum ChapterRelationType {
    /**
     * A 를 이해해야 B 를 이해할 수 있다. <b>단단한 의존</b>이다.
     *
     * <p>이 타입만 순환을 금지한다. 순환이 있으면 어느 챕터도 선행 조건을 만족시킬 수 없어 진입점이
     * 사라진다 — 그리고 그건 조회 시점에 에러가 아니라 "빈 추천"으로 나타난다.
     */
    PREREQUISITE,

    /** 서로 도움이 되지만 순서는 없다. 관심 기반 추천에 쓴다. */
    RELATED,

    /** B 가 A 의 심화다. 이해도가 높은 사용자에게 제시한다. */
    DEEPENS
}
